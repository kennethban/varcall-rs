#!/usr/bin/env python3
"""doc.py: writes docs/gatk-arguments.md from `variant-rs <Tool> --help`, for every GATK tool variant-rs takes.
Run from the repository root after a build, whenever the argument tables (gen.py) or gatk_cli.rs change:
    python3 variant-rs/gatkargs/doc.py [path/to/variant-rs]
"""
import re
import subprocess
import sys

V = sys.argv[1] if len(sys.argv) > 1 else "target/release/variant-rs"
OUT = "docs/gatk-arguments.md"


def run(*args):
    p = subprocess.run([V, *args], capture_output=True, text=True)
    return p.stdout + p.stderr


# the tool list, as variant-rs prints it for a tool it does not take
m = re.search(r"\(supported: ([^)]*)\)", run("NoSuchTool", "--help"))
if not m:
    sys.exit(f"doc.py: no tool list from {V}")
tools = [t.strip() for t in m.group(1).split(",")]


def sections(text):
    """The help's lists: mapped (one argument per line), ignored and variant-rs options (one line each)."""
    out, cur = {}, None
    for line in text.splitlines():
        if line.startswith("Arguments mapped"):
            cur = "mapped"
        elif line.startswith("Ignored"):
            cur = "ignored"
        elif line.startswith("variant-rs options"):
            cur = "extras"
        elif line.startswith("  ") and cur:
            out.setdefault(cur, []).extend(line.split())
        else:
            cur = None
    return out


def fmt(args):
    # "--input,-I" -> `--input` / `-I`
    return ", ".join(" / ".join(f"`{n}`" for n in a.split(",")) for a in args) if args else "none"


lines = [
    "# GATK arguments, tool by tool",
    "",
    "<!-- Generated by variant-rs/gatkargs/doc.py from `variant-rs <Tool> --help`; do not edit by hand. -->",
    "",
    "For each GATK tool it takes, variant-rs sorts GATK 4.7's arguments into three groups:",
    "",
    "* **mapped:** variant-rs implements the argument. Some mapped arguments take only some values (SortSam only",
    "  `coordinate`, for example): a value it does not reproduce is refused with the reason;",
    "* **ignored:** the argument cannot change the output (logging, temporary files, JVM and cloud settings);",
    "* **every other argument is accepted only at GATK's default value**, and refused otherwise.",
    "",
    "A refused command exits with status 2, or runs the real GATK under `GATK_FALLBACK=/path/to/gatk`.",
    "`VARIANT_RS_DRY_RUN=1 variant-rs <Tool> ...` shows which would happen. `variant-rs <Tool> --help` prints the same",
    "lists. What variant-rs does not cover at all: [reference.md](reference.md#unsupported-features).",
    "",
    " · ".join(f"[{t}](#{t.lower()})" for t in tools),
]
for t in tools:
    s = sections(run(t, "--help"))
    if "mapped" not in s:
        sys.exit(f"doc.py: unexpected --help output for {t}")
    lines += [
        "",
        f"## {t}",
        "",
        f"* **Mapped:** {fmt(s.get('mapped'))}",
        f"* **Ignored:** {fmt(s.get('ignored'))}",
        f"* **variant-rs's own options:** {fmt(s.get('extras'))}",
    ]
open(OUT, "w").write("\n".join(lines) + "\n")
print(f"wrote {OUT} ({len(tools)} tools)")
